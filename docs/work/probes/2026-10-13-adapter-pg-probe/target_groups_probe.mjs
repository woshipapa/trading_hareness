import { freshLedger, stepper, mod, runSchema, realWebhooks } from './lib.mjs';
const { createTargetGroups } = await mod('target-groups.mjs');
const { createTargetRegistry } = await mod('target-registry.mjs');
const { createTargetMembers } = await mod('target-members.mjs');
const { createJoinLink } = await mod('join-link.mjs');
const { ledger, pool } = await freshLedger('probe_tg');
const S = stepper();
const now = () => new Date('2026-10-13T02:30:00Z');
const wh = await realWebhooks(ledger, now);
const calls = [];
const bridgePost = async (route, body) => { calls.push(route); if (route === '/target-groups/create') return { chat_id: 7770001 }; if (route === '/target-groups/invite') return { link: 'https://x/invite' }; return { status: 'ok' }; };
const reg = createTargetRegistry({ ledger, bridgePost, webhookTargets: wh, now });
await runSchema(ledger, reg);
let refreshed = 0; const refreshGroups = async () => { refreshed += 1; };
const tg = createTargetGroups({ bridgePost, targetRegistry: reg, webhookTargets: wh, refreshGroups });
const tm = createTargetMembers({ bridgePost, targetRegistry: reg });
const jl = createJoinLink({ bridgePost, refreshGroups });
const r = (f, m, p) => f.routes.find((x) => x.method === m && x.path.endsWith(p));
let created;
await S.step('create group (webhook-targets save + registry write)', async () => { created = await r(tg, 'POST', '/target-groups').handle({ body: { name: '新目标群', keyword: '' } }); return [created.target.chat_id.slice(0, 5), created.target.managed, refreshed]; });
await S.step('registry row stored', async () => (await pool.query('SELECT chat_id, websocket_chat_id, owned FROM feishu_group_relay_target_groups')).rows.length);
await S.step('invite for target', async () => r(tg, 'POST', '/invite').handle({ params: { chatId: created.target.chat_id } }));
await S.step('members list', async () => r(tm, 'GET', '/members').handle({ params: { chatId: created.target.chat_id } }));
await S.step('members history with cursor', async () => r(tm, 'GET', '/history').handle({ params: { chatId: created.target.chat_id }, query: new URLSearchParams('cursor=3') }));
await S.step('applications', async () => r(tm, 'GET', '/applications').handle({ params: { chatId: created.target.chat_id } }));
await S.step('member remove', async () => r(tm, 'DELETE', '/members/:userId').handle({ params: { chatId: created.target.chat_id, userId: '42' } }));
await S.step('join link info + join', async () => { await r(jl, 'POST', '/link-info').handle({ body: {} }); await r(jl, 'POST', '/join').handle({ body: {} }); return refreshed; });
S.done(); process.exit(S.failed ? 1 : 0);
